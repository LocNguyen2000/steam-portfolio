create table if not exists public.guestbook_entries (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(btrim(name)) between 1 and 40),
  message text not null check (char_length(btrim(message)) between 1 and 500),
  created_at timestamptz not null default now()
);

alter table public.guestbook_entries enable row level security;

revoke all on table public.guestbook_entries from public, anon, authenticated;
grant select, insert on table public.guestbook_entries to anon;
revoke all on sequence public.guestbook_entries_id_seq
  from public, anon, authenticated;
grant usage, select on sequence public.guestbook_entries_id_seq to anon;

drop policy if exists "Anyone can read guest-book entries"
  on public.guestbook_entries;
create policy "Anyone can read guest-book entries"
  on public.guestbook_entries
  for select
  to anon
  using (true);

drop policy if exists "Anyone can add a guest-book entry"
  on public.guestbook_entries;
create policy "Anyone can add a guest-book entry"
  on public.guestbook_entries
  for insert
  to anon
  with check (
    char_length(btrim(name)) between 1 and 40
    and char_length(btrim(message)) between 1 and 500
  );
